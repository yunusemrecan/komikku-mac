"""
Prepare the interpreter so upstream Komikku modules can be imported on macOS.

Must run before anything imports `komikku` or `gi`.
"""

import logging
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHIM_DIR = os.path.join(HERE, 'shim')

_done = False


def find_upstream_root():
    """Directory containing upstream's `komikku` package and `data` folder."""
    candidates = [
        os.environ.get('KOMIKKU_UPSTREAM'),
        # Inside the .app bundle: Resources/backend/komikku_mac -> Resources/upstream
        os.path.join(HERE, '..', '..', 'upstream'),
        # Repository checkout: backend/komikku_mac -> upstream
        os.path.join(HERE, '..', '..', 'upstream'),
    ]
    for candidate in candidates:
        if candidate and os.path.isdir(os.path.join(candidate, 'komikku', 'servers')):
            return os.path.abspath(candidate)
    raise RuntimeError('Upstream Komikku sources not found (set KOMIKKU_UPSTREAM)')


def bootstrap():
    global _done
    if _done:
        return
    _done = True

    upstream = find_upstream_root()

    # Our `gi` must win over any real PyGObject
    sys.path.insert(0, SHIM_DIR)
    sys.path.insert(1, upstream)

    from gi import _gio as Gio
    from gi import _glib as GLib

    data_dir = os.path.join(GLib.get_user_data_dir(), 'komikku')
    os.makedirs(data_dir, exist_ok=True)

    Gio.SCHEMA_PATH = os.path.join(upstream, 'data', 'info.febvre.Komikku.gschema.xml.in')
    Gio.SETTINGS_PATH = os.path.join(data_dir, 'settings.json')

    # Upstream `komikku/__init__.py` may be absent from the source tree (generated by meson)
    import importlib.util
    if importlib.util.find_spec('komikku') is None:
        raise RuntimeError(f'`komikku` package not importable from {upstream}')

    # Replace WebKitGTK-based helpers with the bridge to the Swift frontend
    from komikku_mac import webview_bridge
    webview_bridge.install()

    # Server credentials in the macOS Keychain
    from komikku_mac import keychain
    keychain.install()

    logging.getLogger('komikku_mac').debug('Bootstrapped with upstream at %s', upstream)
